// Makes the load-test accounts: out/accounts.csv (email + session id, read by
// k6) and out/auth-seed.sql (users, remorse-chess role and 24h sessions, run
// against the lcruz_auth DB). Re-running makes new sessions and the seed
// replaces the old ones.
// Usage: node loadtest/remorse-chess/accounts.mjs [count=100] [cookieDomain=lcruz.dev]
import { randomBytes } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const count = Number(process.argv[2] ?? 100);
const domain = process.argv[3] ?? 'lcruz.dev';
if (!Number.isInteger(count) || count < 2) {
  throw new Error('count must be a whole number, at least 2');
}

const out = path.join(import.meta.dirname, 'out');
const accounts = Array.from({ length: count }, (_, i) => {
  const n = String(i + 1).padStart(3, '0');
  return {
    name: `Load test ${n}`,
    email: `loadtest-${n}@loadtest.invalid`,
    sessionId: randomBytes(32).toString('base64url'),
  };
});

const rows = (format) => accounts.map(format).join(',\n  ');

const seed = `-- Generated by accounts.mjs. Run against the lcruz_auth DB.
BEGIN;
DELETE FROM user_sessions WHERE email LIKE 'loadtest-%@loadtest.invalid';
INSERT INTO users (name, email) VALUES
  ${rows((a) => `('${a.name}', '${a.email}')`)}
ON CONFLICT (email) DO NOTHING;
INSERT INTO user_roles (email, app, role) VALUES
  ${rows((a) => `('${a.email}', 'remorse-chess', 'user')`)}
ON CONFLICT DO NOTHING;
INSERT INTO user_sessions (session_id, email, expires_at, domain) VALUES
  ${rows(
    (a) =>
      `('${a.sessionId}', '${a.email}', now() + interval '24 hours', '${domain}')`,
  )};
COMMIT;
`;

const csv = [
  'email,session_id',
  ...accounts.map((a) => `${a.email},${a.sessionId}`),
  '',
].join('\n');

await mkdir(out, { recursive: true });
await writeFile(path.join(out, 'auth-seed.sql'), seed);
await writeFile(path.join(out, 'accounts.csv'), csv);
console.log(`Wrote ${count} accounts to ${out}/accounts.csv and auth-seed.sql`);
